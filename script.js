let currentMovie = null;
let currentTab = "intro";
let favorites = JSON.parse(localStorage.getItem("cineworldFavorites") || "[]");

function hideAllViews() {
  document.querySelectorAll("main > section").forEach(section => {
    section.classList.add("hidden");
  });
}

function showHome() {
  hideAllViews();
  document.getElementById("homeView").classList.remove("hidden");
  renderFeatured();
  window.scrollTo(0, 0);
}

function showMovies() {
  hideAllViews();
  document.getElementById("moviesView").classList.remove("hidden");
  document.getElementById("searchBox").value = "";
  renderMovies(movies);
  window.scrollTo(0, 0);
}

function showFavorites() {
  hideAllViews();
  document.getElementById("favoritesView").classList.remove("hidden");
  const savedMovies = movies.filter(movie => favorites.includes(movie.title));
  renderMovies(savedMovies, "favoriteGrid");
  window.scrollTo(0, 0);
}

function showAbout() {
  hideAllViews();
  document.getElementById("aboutView").classList.remove("hidden");
  window.scrollTo(0, 0);
}

function showContact() {
  hideAllViews();
  document.getElementById("contactView").classList.remove("hidden");
  window.scrollTo(0, 0);
}

function renderFeatured() {
  renderMovies(movies.slice(0, 4), "featuredMovies");
}

function renderMovies(list, containerId = "movieGrid") {
  const container = document.getElementById(containerId);

  if (list.length === 0) {
    container.innerHTML = '<p class="empty-message">No movies found. Try another search.</p>';
    return;
  }

  container.innerHTML = list.map(movie => `
    <article class="movie-card">
      <div class="poster">${movie.title}</div>
      <div class="card-info">
        <h3>${movie.title}</h3>
        <p>${movie.year} | ${movie.genre}</p>
        <div class="card-actions">
          <button onclick="openMovie('${movie.title}')">View Details</button>
          <button class="fav-btn" title="Add to favorites"
            onclick="toggleFavorite('${movie.title}')">
            ${favorites.includes(movie.title) ? "♥" : "♡"}
          </button>
        </div>
      </div>
    </article>
  `).join("");
}

function searchMovies() {
  const value = document.getElementById("searchBox").value.toLowerCase().trim();
  const filtered = movies.filter(movie =>
    movie.title.toLowerCase().includes(value) ||
    movie.genre.toLowerCase().includes(value)
  );
  renderMovies(filtered);
}

function toggleFavorite(title) {
  if (favorites.includes(title)) {
    favorites = favorites.filter(item => item !== title);
  } else {
    favorites.push(title);
  }

  localStorage.setItem("cineworldFavorites", JSON.stringify(favorites));

  if (!document.getElementById("favoritesView").classList.contains("hidden")) {
    showFavorites();
  } else if (!document.getElementById("moviesView").classList.contains("hidden")) {
    searchMovies();
  } else {
    renderFeatured();
  }
}

function openMovie(title) {
  currentMovie = movies.find(movie => movie.title === title);
  if (!currentMovie) return;

  currentTab = "intro";
  hideAllViews();
  document.getElementById("detailsView").classList.remove("hidden");
  renderMovieDetails();
  window.scrollTo(0, 0);
}

function renderMovieDetails() {
  const movie = currentMovie;
  const container = document.getElementById("movieDetails");

  container.innerHTML = `
    <div class="detail-hero">
      <div class="detail-poster">${movie.title}</div>
      <div>
        <p class="tagline">CINEWORLD MOVIE COLLECTION</p>
        <h1>${movie.title}</h1>
        <p class="movie-meta">${movie.year} | ${movie.genre}</p>
        <p><strong>Director:</strong> ${movie.director}</p>
        <p><strong>Producer:</strong> ${movie.producer}</p>
        <p style="margin-top:15px;color:#bbb">
          Read the complete movie information using the sections below.
        </p>
        <button class="primary-btn" style="margin-top:15px"
          onclick="toggleFavorite('${movie.title}')">
          ${favorites.includes(movie.title) ? "♥ Remove Favorite" : "♡ Add to Favorites"}
        </button>
      </div>
    </div>

    <div class="movie-tabs">
      ${tabs.map(tab => `
        <button class="${currentTab === tab[0] ? "active" : ""}"
          onclick="changeTab('${tab[0]}')">${tab[1]}</button>
      `).join("")}
    </div>

    <div id="detailPage" class="detail-page"></div>
  `;

  renderCurrentTab();
}

function changeTab(tabName) {
  currentTab = tabName;
  renderMovieDetails();
}

function renderCurrentTab() {
  const movie = currentMovie;
  let heading = "";
  let content = "";

  if (currentTab === "cast") {
    heading = "Cast and Characters";
    content = `
      <p><strong>Director:</strong> ${movie.director}</p>
      <p><strong>Producer:</strong> ${movie.producer}</p>
      <p><strong>Actors:</strong> ${movie.actors}</p>
      <p><strong>Actresses:</strong> ${movie.actress}</p>
    `;
  } else {
    const labels = {
      intro: "Introduction of the Movie",
      story: "Complete Story",
      action: "Action and Main Events",
      message: "Main Message",
      motivation: "Motivation and Learning",
      conclusion: "Conclusion",
      uses: "Uses and Applications"
    };

    heading = labels[currentTab];
    content = `<p>${movie[currentTab]}</p>`;
  }

  document.getElementById("detailPage").innerHTML = `
    <h2>${heading}</h2>
    ${content}
  `;
}

function sendMessage(event) {
  event.preventDefault();

  const name = document.getElementById("contactName").value;
  document.getElementById("contactStatus").textContent =
    "Thank you, " + name + "! Your message has been entered. This demo website does not send messages to a server.";

  event.target.reset();
}

